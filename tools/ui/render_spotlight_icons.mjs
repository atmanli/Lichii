// Renders the Spotlight icons (Phosphor Icons, MIT) in spotlight/svg/ to white 64 px masks that
// Spotlight::Icon tints at runtime, and lists them with the fonts in spotlight.qrc.
// Needs @resvg/resvg-js:
//   npm i @resvg/resvg-js && node tools/ui/render_spotlight_icons.mjs
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { Resvg } from "@resvg/resvg-js";

const root = new URL("../../dist/qt_themes/lichii/", import.meta.url);
const src = new URL("spotlight/svg/", root);
const out = new URL("spotlight/icons/", root);
mkdirSync(out, { recursive: true });

const icons = readdirSync(src).filter((f) => f.endsWith(".svg")).sort();
for (const file of icons) {
    const svg = readFileSync(new URL(file, src), "utf8").replaceAll("currentColor", "#ffffff");
    const png = new Resvg(svg, { fitTo: { mode: "width", value: 64 } }).render().asPng();
    writeFileSync(new URL(file.replace(".svg", ".png"), out), png);
}

const fonts = readdirSync(new URL("spotlight/fonts/", root)).filter((f) => f.endsWith(".ttf")).sort();
const files = [
    ...icons.map((f) => `spotlight/icons/${f.replace(".svg", ".png")}`),
    ...fonts.map((f) => `spotlight/fonts/${f}`),
];
writeFileSync(
    new URL("spotlight.qrc", root),
    `<!--
SPDX-FileCopyrightText: Copyright 2026 Lichii Project
SPDX-License-Identifier: GPL-3.0-or-later
-->

<!-- Generated by tools/ui/render_spotlight_icons.mjs. -->
<RCC>
    <qresource prefix="/">
${files.map((f) => `        <file>${f}</file>`).join("\n")}
    </qresource>
</RCC>
`,
);
